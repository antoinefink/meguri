//! Checked review-format edits of one existing template (structure-changes
//! S1–S3, S7–S9). The captured ordinal identifies the template; its optional
//! ID is only a crosscheck. This operation cannot edit a layout or options.

use std::sync::Arc;
use std::time::Duration;

use meguri_model::changes::OpSource;
use meguri_model::ids::{CardId, NotetypeId};
use meguri_model::notetype::{Notetype, NotetypeTemplate};
use meguri_storage::{ReadRows, ReaderRole, Table, WriteScope};

use super::{AggregateDigest, names, validate, write};
use crate::cardgen::regenerate::{self, RegenerationPlan};
use crate::executor::catalog;
use crate::undo::{entry::StepKind, names::UPDATE_NOTE_TYPE};
use crate::{CancelToken, Collection, EngineError, OpResult, OpSpec, Plan, ProgressSink};

/// Identity captured with the base aggregate. Missing or repeated legacy
/// IDs do not replace the stored ordinal as the lookup key.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct TemplateIdentity {
    pub ord: u32,
    pub id: Option<i64>,
}

impl TemplateIdentity {
    pub fn of(template: &NotetypeTemplate) -> Self {
        Self {
            ord: template.ord,
            id: template.config.id,
        }
    }
}

/// Replace one existing template's review front/back and optionally the
/// type's CSS. Browser formats, names, options and layout are retained.
/// There is deliberately no unchecked-save or schema-confirmation input.
#[derive(Clone, Debug)]
pub struct TemplateFormatsUpdate {
    pub notetype: NotetypeId,
    pub base: AggregateDigest,
    pub template: TemplateIdentity,
    pub front: String,
    pub back: String,
    pub css: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TemplateFormatsSaved {
    pub id: NotetypeId,
    pub written: bool,
    /// Only cards newly generated by this transaction, in G9's order.
    pub cards_added: Vec<CardId>,
}

/// Private contents bind the checked candidate and G9 plan to their base.
#[derive(Clone, Debug)]
pub struct TemplateFormatsPlan {
    request: TemplateFormatsUpdate,
    updated: Notetype,
    changed: bool,
    regeneration: Option<RegenerationPlan>,
}

fn invalid(message: &str) -> EngineError {
    EngineError::InvalidArgument {
        message: message.to_owned(),
    }
}

fn stale(id: NotetypeId) -> EngineError {
    EngineError::Stale {
        table: Table::Notetypes,
        key: id.0.to_string(),
    }
}

fn base(reader: &impl ReadRows, request: &TemplateFormatsUpdate) -> Result<Notetype, EngineError> {
    let stored = reader
        .notetype(request.notetype)?
        .ok_or_else(|| invalid("unknown note type"))?;
    // S1.2: invalid origins precede the stale-base refusal. A one-template
    // request cannot repeat an origin, add, remove or reorder a template.
    let template = stored
        .templates
        .iter()
        .find(|template| template.ord == request.template.ord)
        .ok_or_else(|| invalid("template ordinal is out of range"))?;
    if AggregateDigest::of(&stored) != request.base {
        return Err(stale(request.notetype));
    }
    // Crosscheck the optional ID only against a matching captured base.
    if template.config.id != request.template.id {
        return Err(invalid("template ordinal no longer identifies the captured template ID"));
    }
    Ok(stored)
}

/// Plan on the reader snapshot with the original base, always checking V3.
/// Only changed fronts recompute requirements and invoke G9; no-op saves
/// neither repair old requirements nor normalize unrelated stored members.
pub fn plan(
    reader: &impl ReadRows,
    request: TemplateFormatsUpdate,
    cancel: &CancelToken,
    progress: &ProgressSink,
) -> Result<TemplateFormatsPlan, EngineError> {
    cancel.check()?;
    let stored = base(reader, &request)?;
    let mut updated = stored.clone();
    let template = updated
        .templates
        .iter_mut()
        .find(|template| template.ord == request.template.ord)
        .expect("validated template identity");
    let fronts_changed = template.config.q_format != request.front;
    let changed = fronts_changed
        || template.config.a_format != request.back
        || request.css.as_ref().is_some_and(|css| *css != updated.config.css);
    template.config.q_format.clone_from(&request.front);
    template.config.a_format.clone_from(&request.back);
    if let Some(css) = &request.css {
        updated.config.css.clone_from(css);
    }
    // V2 refusals still apply, but this narrow request has no names or
    // layout to normalize. Never persist normalization of retained rows.
    names::normalize(&mut updated.clone(), &[])?;
    if let Some(failure) = validate::first_failure(&updated) {
        return Err(failure.into());
    }
    let regeneration = if fronts_changed {
        updated.config.reqs = write::card_requirements(&updated)
            .into_iter()
            .map(|computed| {
                // Keep opaque metadata on each retained requirement.
                let mut requirement = stored
                    .config
                    .reqs
                    .iter()
                    .find(|old| old.card_ord == computed.card_ord)
                    .cloned()
                    .unwrap_or_default();
                requirement.card_ord = computed.card_ord;
                requirement.kind = computed.kind;
                requirement.field_ords = computed.field_ords;
                requirement
            })
            .collect();
        Some(regenerate::plan(reader, &updated, cancel, progress)?)
    } else {
        None
    };
    cancel.check()?;
    Ok(TemplateFormatsPlan {
        request,
        updated,
        changed,
        regeneration,
    })
}

/// Recheck the exact aggregate inside the writer transaction before any
/// write. N3's row writer and G9 share the executor journal and undo step.
/// Formats/CSS alone require no structure report or schema reason.
pub fn commit_in(
    scope: &mut WriteScope<'_>,
    planned: &TemplateFormatsPlan,
) -> Result<TemplateFormatsSaved, EngineError> {
    base(scope, &planned.request)?;
    if !planned.changed {
        return Ok(TemplateFormatsSaved {
            id: planned.updated.id,
            written: false,
            cards_added: Vec::new(),
        });
    }
    let written = scope.put_notetype(&planned.updated)?;
    let cards_added = match &planned.regeneration {
        Some(regeneration) => regenerate::commit_in(scope, regeneration)?,
        None => Vec::new(),
    };
    Ok(TemplateFormatsSaved {
        id: planned.updated.id,
        written: written.changed(),
        cards_added,
    })
}

/// Blocking worker entry point. Planning is cancellable; once the writer
/// passes its cancel point the aggregate and generation complete atomically.
/// The original base is never refreshed and a stale plan is never rebuilt.
pub fn update_template_formats(
    collection: &Collection,
    request: TemplateFormatsUpdate,
    cancel: Arc<CancelToken>,
    progress: ProgressSink,
) -> Result<OpResult<TemplateFormatsSaved>, EngineError> {
    let spec = OpSpec::new(catalog::NOTETYPE_STRUCTURE_CHANGE, OpSource::UserUndoable)
        .undo_step(UPDATE_NOTE_TYPE, StepKind::Other)
        .cancel(cancel.clone())
        .progress(progress.clone());
    crate::plan_and_commit_with(
        collection,
        ReaderRole::Maintenance,
        spec,
        |context| {
            // The shared executor offers a retry after Stale. S1.2 forbids
            // replanning this captured draft, even if the rows change back.
            if context.attempt() != 0 {
                return Err(stale(request.notetype));
            }
            Ok(Plan {
                value: plan(&**context.snapshot(), request.clone(), &cancel, &progress)?,
                preconditions: Vec::new(),
            })
        },
        |spec, planned| {
            if planned.regeneration.is_some() {
                spec.clone().declare_long_write(Duration::from_secs(1))
            } else {
                spec.clone()
            }
        },
        |context, planned| commit_in(context.scope(), &planned),
    )
}
