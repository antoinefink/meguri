#!/usr/bin/env python3
"""Writes src/unicode10_unassigned.rs: the code points that are unassigned
(General_Category Cn) in Unicode 10.0.0, for media-filenames.md F1 step 2.

Input: UnicodeData.txt of the Unicode 10.0.0 character database,
https://www.unicode.org/Public/10.0.0/ucd/UnicodeData.txt, checked against
the SHA-256 below. A code point is assigned when the file lists it, alone or
inside a `<..., First>` / `<..., Last>` range; every other code point,
noncharacters included, is Cn.

Usage: python3 -I gen/unicode10_unassigned.py <UnicodeData.txt> > src/unicode10_unassigned.rs
"""

import hashlib
import sys

SHA256 = "52423e4d7492167b62f518f68d54db88930abbbff7f11edfcaec8f726498cab1"
MAX = 0x10FFFF


def assigned_ranges(lines):
    ranges = []
    first = None
    for line in lines:
        if not line.strip():
            continue
        fields = line.split(";")
        cp = int(fields[0], 16)
        name = fields[1]
        if name.endswith(", First>"):
            first = cp
            continue
        if name.endswith(", Last>"):
            if first is None:
                raise SystemExit(f"range end {cp:04X} without a start")
            ranges.append((first, cp))
            first = None
            continue
        ranges.append((cp, cp))
    ranges.sort()
    merged = []
    for lo, hi in ranges:
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
        else:
            merged.append((lo, hi))
    return merged


def gaps(assigned):
    out = []
    next_cp = 0
    for lo, hi in assigned:
        if lo > next_cp:
            out.append((next_cp, lo - 1))
        next_cp = hi + 1
    if next_cp <= MAX:
        out.append((next_cp, MAX))
    return out


def main():
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"UnicodeData.txt has SHA-256 {digest}, expected {SHA256}")
    unassigned = gaps(assigned_ranges(data.decode("utf-8").split("\n")))
    out = sys.stdout
    out.write("// Generated by gen/unicode10_unassigned.py from the Unicode 10.0.0\n")
    out.write(f"// UnicodeData.txt (SHA-256 {SHA256}).\n")
    out.write("// Do not edit; rerun the script.\n\n")
    out.write("/// Inclusive ranges of the code points that are unassigned (Cn) in\n")
    out.write("/// Unicode 10.0.0, sorted and disjoint.\n")
    out.write("#[rustfmt::skip]\n")
    out.write(f"pub(crate) static UNASSIGNED: [(u32, u32); {len(unassigned)}] = [\n")
    for lo, hi in unassigned:
        out.write(f"    (0x{lo:04X}, 0x{hi:04X}),\n")
    out.write("];\n")


if __name__ == "__main__":
    main()
