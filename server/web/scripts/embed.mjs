import { createHash } from "node:crypto";
import { copyFile, lstat, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { copySource } from "./copy-source.mjs";
const [inputArg, outputArg] = process.argv.slice(2);
if (!inputArg || !outputArg) throw new Error("Usage: embed.mjs <vite-dist> <output-directory>");
const input = resolve(inputArg), output = resolve(outputArg);
const noticePath = process.env.MEGURI_WEB_NOTICES_FILE;
if (!noticePath) throw new Error("Missing required distributed-code notices");
const requiredNotices = [await readFile(new URL("../THIRD_PARTY_NOTICES.txt", import.meta.url)), await readFile(noticePath)];
if (requiredNotices.some(bytes => !bytes.toString("utf8").trim())) throw new Error("Required license notices are empty");
const embedded = resolve(output, "embedded");
await mkdir(embedded, { recursive: true });
const names = ["index.html", ...(await readdir(resolve(input, "assets"))).sort().map(name => `assets/${name}`)];
const inventory = [], rows = [];
let scripts = 0;
for (const name of names) {
  if (name !== "index.html" && !/^assets\/[A-Za-z0-9_.-]+-[A-Za-z0-9_-]{8,}\.(js|css)$/.test(name)) throw new Error("Unexpected build artifact; no maps or remote assets allowed");
  const source = resolve(input, name), stat = await lstat(source);
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error("Expected a regular build file");
  const bytes = await readFile(source);
  if (!bytes.length) throw new Error("Empty asset");
  if (name === "index.html" && (/https?:\/\//i.test(bytes.toString()) || /<script(?![^>]*\bsrc=)/i.test(bytes.toString()))) throw new Error("Unexpected inline or remote entry");
  if (name.endsWith(".js")) {
    scripts++;
    if (requiredNotices.some(notice => !bytes.includes(notice))) throw new Error(`Compiled JavaScript is missing full license notice bytes: ${name}`);
  }
  const targetName = name.replaceAll("/", "_");
  await copyFile(source, resolve(embedded, targetName));
  const mime = name.endsWith(".html") ? "text/html; charset=utf-8" : name.endsWith(".css") ? "text/css; charset=utf-8" : "text/javascript; charset=utf-8";
  const row = `Asset { path: ${JSON.stringify("/" + name)}, content_type: ${JSON.stringify(mime)}, bytes: include_bytes!(concat!(env!("OUT_DIR"), "/embedded/${targetName}")) }`;
  if (name === "index.html") rows.unshift(`static INDEX: Asset = ${row};`); else rows.push(row);
  inventory.push({ path: "/" + name, sha256: createHash("sha256").update(bytes).digest("hex"), bytes: bytes.length });
}
if (!scripts) throw new Error("No compiled JavaScript to verify");
await writeFile(resolve(output, "meguri_web_assets.rs"), `// Generated by embed.mjs; do not edit.\n${rows[0]}\nstatic ASSETS: &[Asset] = &[\n${rows.slice(1).join(",\n")}\n];\n`);
await writeFile(resolve(output, "assets.json"), JSON.stringify(inventory, null, 2) + "\n");
// Bind preparation to the exact local build inputs, without a Cargo build
// dependency or a timestamp-based stale-input exception.
const web = fileURLToPath(new URL("../", import.meta.url));
await copySource(web, resolve(output, "inputs"));
